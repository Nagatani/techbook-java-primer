public class DebugExample {
    public static void main(String[] args) {
        int a = 10;
        int b = 20;
        
        System.out.println("a = " + a);  // デバッグ出力
        System.out.println("b = " + b);  // デバッグ出力
        
        int sum = a + b;
        System.out.println("sum = " + sum);  // 計算結果を確認
    }
}
