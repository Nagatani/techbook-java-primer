import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;

/**
 * ToDoリストのCRUD（課題2の解答例）
 */
public class TodoCrud {
    private static final String CREATE_TABLE_SQL = """
        CREATE TABLE todos (
            id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            title VARCHAR(100) NOT NULL,
            done BOOLEAN DEFAULT FALSE NOT NULL
        )
        """;

    public static void main(String[] args) {
        try (Connection conn = DriverManager.getConnection("jdbc:h2:mem:todo", "sa", "")) {
            createTable(conn);

            IO.println("=== 追加（CREATE） ===");
            String[] titles = {"レポートを出す", "図書館で本を返す", "サークルの会費を払う", "英単語を30個覚える"};
            for (String title : titles) {
                int id = add(conn, title);
                IO.println("追加しました: " + id + " " + title);
            }

            IO.println();
            IO.println("=== 一覧（READ） ===");
            listAll(conn).forEach(IO::println);

            IO.println();
            IO.println("=== 完了にする（UPDATE） ===");
            IO.println("2を完了: " + markDone(conn, 2));
            IO.println("4を完了: " + markDone(conn, 4));
            IO.println("9を完了: " + markDone(conn, 9));
            listAll(conn).forEach(IO::println);

            IO.println();
            IO.println("=== 削除（DELETE） ===");
            IO.println("1を削除: " + delete(conn, 1));
            IO.println("1をもう一度削除: " + delete(conn, 1));
            IO.println("完了したものを削除: " + deleteDone(conn) + "件");
            listAll(conn).forEach(IO::println);
        } catch (SQLException e) {
            System.err.println("データベースのエラー: " + e.getMessage());
        }
    }

    public static void createTable(Connection conn) throws SQLException {
        try (Statement stmt = conn.createStatement()) {
            stmt.execute(CREATE_TABLE_SQL);
        }
    }

    /** ToDoを追加し、データベースが振ったIDを返す */
    public static int add(Connection conn, String title) throws SQLException {
        String sql = "INSERT INTO todos (title) VALUES (?)";
        try (PreparedStatement pstmt = conn.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {
            pstmt.setString(1, title);
            pstmt.executeUpdate();
            try (ResultSet keys = pstmt.getGeneratedKeys()) {
                if (keys.next()) {
                    return keys.getInt(1);
                }
                throw new SQLException("IDを取得できませんでした");
            }
        }
    }

    /** 「[x] 2 図書館で本を返す」の形の文字列をID順に返す */
    public static List<String> listAll(Connection conn) throws SQLException {
        List<String> lines = new ArrayList<>();
        try (Statement stmt = conn.createStatement();
             ResultSet rs = stmt.executeQuery("SELECT id, title, done FROM todos ORDER BY id")) {
            while (rs.next()) {
                String mark = rs.getBoolean("done") ? "[x]" : "[ ]";
                lines.add(mark + " " + rs.getInt("id") + " " + rs.getString("title"));
            }
        }
        return lines;
    }

    /** 完了にできたらtrue（IDがなければfalse） */
    public static boolean markDone(Connection conn, int id) throws SQLException {
        try (PreparedStatement pstmt = conn.prepareStatement("UPDATE todos SET done = TRUE WHERE id = ?")) {
            pstmt.setInt(1, id);
            return pstmt.executeUpdate() > 0;
        }
    }

    /** 削除できたらtrue（IDがなければfalse） */
    public static boolean delete(Connection conn, int id) throws SQLException {
        try (PreparedStatement pstmt = conn.prepareStatement("DELETE FROM todos WHERE id = ?")) {
            pstmt.setInt(1, id);
            return pstmt.executeUpdate() > 0;
        }
    }

    /** 完了したToDoをまとめて削除し、削除した件数を返す */
    public static int deleteDone(Connection conn) throws SQLException {
        try (PreparedStatement pstmt = conn.prepareStatement("DELETE FROM todos WHERE done = TRUE")) {
            return pstmt.executeUpdate();
        }
    }
}
