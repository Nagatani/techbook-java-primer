import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.List;

/**
 * テーブルの作成と、本・利用者の一括登録
 */
public class LibraryDatabase {
    private static final String[] CREATE_TABLES = {
        """
        CREATE TABLE books (
            id VARCHAR(10) PRIMARY KEY,
            title VARCHAR(100) NOT NULL,
            author VARCHAR(50) NOT NULL,
            on_loan BOOLEAN DEFAULT FALSE NOT NULL
        )
        """,
        """
        CREATE TABLE members (
            id INT PRIMARY KEY,
            name VARCHAR(30) NOT NULL
        )
        """,
        """
        CREATE TABLE loans (
            id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            book_id VARCHAR(10) NOT NULL,
            member_id INT NOT NULL,
            loaned_on DATE NOT NULL,
            due_on DATE NOT NULL,
            returned_on DATE,
            fee INT,
            FOREIGN KEY (book_id) REFERENCES books(id),
            FOREIGN KEY (member_id) REFERENCES members(id)
        )
        """,
    };

    public static void createTables(Connection conn) throws SQLException {
        try (Statement stmt = conn.createStatement()) {
            for (String sql : CREATE_TABLES) {
                stmt.execute(sql);
            }
        }
    }

    /** 本をバッチ処理でまとめて登録し、登録した冊数を返す。失敗したら1冊も登録しない */
    public static int registerBooks(Connection conn, List<Book> books) throws SQLException {
        String sql = "INSERT INTO books (id, title, author) VALUES (?, ?, ?)";
        boolean originalAutoCommit = conn.getAutoCommit();
        conn.setAutoCommit(false);
        try (PreparedStatement pstmt = conn.prepareStatement(sql)) {
            for (Book b : books) {
                pstmt.setString(1, b.id());
                pstmt.setString(2, b.title());
                pstmt.setString(3, b.author());
                pstmt.addBatch();
            }
            int count = pstmt.executeBatch().length;
            conn.commit();
            return count;
        } catch (SQLException e) {
            conn.rollback();
            throw e;
        } finally {
            conn.setAutoCommit(originalAutoCommit);
        }
    }

    /** 利用者をバッチ処理でまとめて登録し、登録した人数を返す */
    public static int registerMembers(Connection conn, List<Member> members) throws SQLException {
        String sql = "INSERT INTO members (id, name) VALUES (?, ?)";
        boolean originalAutoCommit = conn.getAutoCommit();
        conn.setAutoCommit(false);
        try (PreparedStatement pstmt = conn.prepareStatement(sql)) {
            for (Member m : members) {
                pstmt.setInt(1, m.id());
                pstmt.setString(2, m.name());
                pstmt.addBatch();
            }
            int count = pstmt.executeBatch().length;
            conn.commit();
            return count;
        } catch (SQLException e) {
            conn.rollback();
            throw e;
        } finally {
            conn.setAutoCommit(originalAutoCommit);
        }
    }
}
