import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.time.LocalDate;
import java.time.LocalDateTime;
import java.util.ArrayList;
import java.util.List;
import java.util.Optional;

/**
 * JDBCで予定を読み書きするDAO
 */
public class JdbcEventDao implements EventDao {
    private static final String CREATE_TABLE_SQL = """
        CREATE TABLE IF NOT EXISTS events (
            id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            title VARCHAR(100) NOT NULL,
            start_at TIMESTAMP NOT NULL,
            end_at TIMESTAMP NOT NULL,
            place VARCHAR(50)
        )
        """;
    private static final String SELECT = "SELECT id, title, start_at, end_at, place FROM events ";

    private final Connection connection;

    public JdbcEventDao(Connection connection) {
        this.connection = connection;
    }

    public void createTable() throws SQLException {
        try (Statement stmt = connection.createStatement()) {
            stmt.execute(CREATE_TABLE_SQL);
        }
    }

    @Override
    public Event create(Event event) throws SQLException {
        String sql = "INSERT INTO events (title, start_at, end_at, place) VALUES (?, ?, ?, ?)";
        try (PreparedStatement pstmt = connection.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {
            pstmt.setString(1, event.title());
            pstmt.setObject(2, event.start());   // LocalDateTimeをTIMESTAMPとして渡す
            pstmt.setObject(3, event.end());
            pstmt.setString(4, event.place());
            pstmt.executeUpdate();
            try (ResultSet keys = pstmt.getGeneratedKeys()) {
                if (keys.next()) {
                    return event.withId(keys.getInt(1));
                }
                throw new SQLException("IDを取得できませんでした");
            }
        }
    }

    @Override
    public Optional<Event> findById(int id) throws SQLException {
        try (PreparedStatement pstmt = connection.prepareStatement(SELECT + "WHERE id = ?")) {
            pstmt.setInt(1, id);
            List<Event> found = query(pstmt);
            return found.isEmpty() ? Optional.empty() : Optional.of(found.get(0));
        }
    }

    @Override
    public List<Event> findOn(LocalDate date) throws SQLException {
        return findBetween(date, date);
    }

    @Override
    public List<Event> findBetween(LocalDate from, LocalDate to) throws SQLException {
        // 「fromの0時以降、toの翌日の0時より前」とすると、toの日の23時台の予定も含まれる
        String sql = SELECT + "WHERE start_at >= ? AND start_at < ? ORDER BY start_at, id";
        try (PreparedStatement pstmt = connection.prepareStatement(sql)) {
            pstmt.setObject(1, from.atStartOfDay());
            pstmt.setObject(2, to.plusDays(1).atStartOfDay());
            return query(pstmt);
        }
    }

    @Override
    public List<Event> findOverlapping(LocalDateTime start, LocalDateTime end) throws SQLException {
        // 2つの時間帯が重なるのは、片方の始まりがもう片方の終わりより前で、その逆も成り立つとき
        String sql = SELECT + "WHERE start_at < ? AND end_at > ? ORDER BY start_at, id";
        try (PreparedStatement pstmt = connection.prepareStatement(sql)) {
            pstmt.setObject(1, end);
            pstmt.setObject(2, start);
            return query(pstmt);
        }
    }

    @Override
    public boolean update(Event event) throws SQLException {
        String sql = "UPDATE events SET title = ?, start_at = ?, end_at = ?, place = ? WHERE id = ?";
        try (PreparedStatement pstmt = connection.prepareStatement(sql)) {
            pstmt.setString(1, event.title());
            pstmt.setObject(2, event.start());
            pstmt.setObject(3, event.end());
            pstmt.setString(4, event.place());
            pstmt.setInt(5, event.id());
            return pstmt.executeUpdate() > 0;
        }
    }

    @Override
    public boolean delete(int id) throws SQLException {
        try (PreparedStatement pstmt = connection.prepareStatement("DELETE FROM events WHERE id = ?")) {
            pstmt.setInt(1, id);
            return pstmt.executeUpdate() > 0;
        }
    }

    private List<Event> query(PreparedStatement pstmt) throws SQLException {
        List<Event> events = new ArrayList<>();
        try (ResultSet rs = pstmt.executeQuery()) {
            while (rs.next()) {
                events.add(new Event(
                        rs.getInt("id"),
                        rs.getString("title"),
                        rs.getObject("start_at", LocalDateTime.class),
                        rs.getObject("end_at", LocalDateTime.class),
                        rs.getString("place")));
            }
        }
        return events;
    }
}
