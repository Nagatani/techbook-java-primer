// DuplicateUser.java - 一意性制約の違反を受け止めて、利用者に伝わる言葉にする
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.SQLException;
import java.sql.SQLIntegrityConstraintViolationException;
import java.sql.Statement;

public class DuplicateUser {
    public static void main(String[] args) throws SQLException {
        try (Connection conn = DriverManager.getConnection("jdbc:h2:mem:testdb", "sa", "")) {
            try (Statement stmt = conn.createStatement()) {
                stmt.execute("CREATE TABLE users (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                    + " username VARCHAR(50) NOT NULL UNIQUE)");
            }
            IO.println(register(conn, "tanaka"));
            IO.println(register(conn, "tanaka"));
        }
    }

    static String register(Connection conn, String username) throws SQLException {
        try (PreparedStatement ps = conn.prepareStatement("INSERT INTO users (username) VALUES (?)")) {
            ps.setString(1, username);
            ps.executeUpdate();
            return username + "を登録しました";
        } catch (SQLIntegrityConstraintViolationException e) {
            // 制約の違反（一意性・外部キー・NOT NULLなど）は、このクラスかその子クラスで届く
            return username + "は使われています（" + e.getSQLState() + "）";
        }
    }
}
