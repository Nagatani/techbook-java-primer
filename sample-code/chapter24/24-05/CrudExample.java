// CrudExample.java - 表を作り、行の追加・検索・更新・削除を行う
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;

public class CrudExample {
    public static void main(String[] args) throws SQLException {
        try (Connection conn = DriverManager.getConnection("jdbc:h2:mem:testdb", "sa", "")) {
            createTable(conn);
            insert(conn, "tanaka", "tanaka@example.com");
            insert(conn, "sato", "sato@example.com");
            printAll(conn);

            IO.println("更新した行: " + updateEmail(conn, "sato", "sato@example.org"));
            IO.println("削除した行: " + delete(conn, "tanaka"));
            IO.println("削除した行: " + delete(conn, "suzuki")); // 存在しない
            printAll(conn);
        }
    }

    // 表を作る（SQL文を1回だけ実行するならStatementでよい）
    static void createTable(Connection conn) throws SQLException {
        try (Statement stmt = conn.createStatement()) {
            stmt.execute("""
                CREATE TABLE users (
                    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    username VARCHAR(50) NOT NULL UNIQUE,
                    email VARCHAR(100) NOT NULL
                )""");
        }
    }

    // 追加（Create）。値は?の位置にsetXxxで渡す
    static void insert(Connection conn, String username, String email) throws SQLException {
        String sql = "INSERT INTO users (username, email) VALUES (?, ?)";
        try (PreparedStatement ps = conn.prepareStatement(sql)) {
            ps.setString(1, username);
            ps.setString(2, email);
            ps.executeUpdate();
        }
    }

    // 検索（Read）。ResultSetを1行ずつ進めて列の値を取り出す
    static void printAll(Connection conn) throws SQLException {
        String sql = "SELECT id, username, email FROM users ORDER BY id";
        try (PreparedStatement ps = conn.prepareStatement(sql);
             ResultSet rs = ps.executeQuery()) {
            while (rs.next()) {
                IO.println("%d %s %s".formatted(
                    rs.getInt("id"), rs.getString("username"), rs.getString("email")));
            }
        }
    }

    // 更新（Update）。戻り値は変わった行の数
    static int updateEmail(Connection conn, String username, String email) throws SQLException {
        String sql = "UPDATE users SET email = ? WHERE username = ?";
        try (PreparedStatement ps = conn.prepareStatement(sql)) {
            ps.setString(1, email);
            ps.setString(2, username);
            return ps.executeUpdate();
        }
    }

    // 削除（Delete）
    static int delete(Connection conn, String username) throws SQLException {
        try (PreparedStatement ps = conn.prepareStatement("DELETE FROM users WHERE username = ?")) {
            ps.setString(1, username);
            return ps.executeUpdate();
        }
    }
}
