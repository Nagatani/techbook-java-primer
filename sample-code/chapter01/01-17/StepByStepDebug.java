public class StepByStepDebug {
    public static void main(String[] args) {
        System.out.println("プログラム開始");
        
        int x = 5;
        System.out.println("x に 5 を代入しました");
        
        int y = x * 2;
        System.out.println("y に x * 2 の結果を代入しました: " + y);
        
        System.out.println("プログラム終了");
    }
}
